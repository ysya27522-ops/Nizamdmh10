// Generates plain text / Markdown representation
export function generateNizamDocumentMarkdown(): string {
  const data = NIZAM_CONSTITUTIONAL_REPORT;
  let md = `# ${data.title}\n\n`;
  md += `**${data.version}** | ${data.classification}\n\n`;
  md += `> ${data.summary}\n\n---\n\n`;

  data.sections.forEach((sec) => {
    md += `## ${sec.title}\n*${sec.subtitle}*\n\n${sec.content}\n\n`;
    if (sec.bullets) {
      sec.bullets.forEach((b) => {
        md += `- **${b.title}**: ${b.desc}\n`;
      });
      md += '\n';
    }
    if (sec.tableData) {
      md += `| السلطة | دورها في النظام الإسلامي | الإدارة والملاحظات |\n`;
      md += `| :--- | :--- | :--- |\n`;
      sec.tableData.forEach((row) => {
        md += `| **${row.role}** | ${row.description} | ${row.notes} |\n`;
      });
      md += '\n';
    }
  });

  return md;
}
